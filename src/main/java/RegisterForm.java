    private void btnRegisterActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRegisterActionPerformed
         String studentID = txtStudentID.getText().trim();
    String fullname = txtFullName.getText().trim();
    String password = String.valueOf(txtPassword.getPassword());
    String confirmPassword = String.valueOf(txtConfirmPassword.getPassword());

    if (studentID.isEmpty() || fullname.isEmpty() || password.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Please fill all fields.");
        return;
    }

    // Student ID format check: 02-2526-030793
    if (!studentID.matches("\\d{2}-\\d{4}-\\d{6}")) {
        JOptionPane.showMessageDialog(this,
                "Student ID must be in the format 00-0000-000000 (numbers and hyphens only).");
        txtStudentID.requestFocus();
        return;
    }

    if (!password.equals(confirmPassword)) {
        JOptionPane.showMessageDialog(this, "Passwords do not match.");
        return;
    }

    try (Connection con = DBconnection.getConnection();
     PreparedStatement ps = con.prepareStatement(
         "INSERT INTO users(student_id, fullname, password, role) VALUES(?,?,?,?)")) {

    ps.setString(1, studentID);
    ps.setString(2, fullname);
    ps.setString(3, password);
    ps.setString(4, "student");

    ps.executeUpdate();

    JOptionPane.showMessageDialog(this,
            "Registration Successful!");

} catch (Exception e) {

    JOptionPane.showMessageDialog(this,
            e.getMessage());
}
    }//GEN-LAST:event_btnRegisterActionPerformed

