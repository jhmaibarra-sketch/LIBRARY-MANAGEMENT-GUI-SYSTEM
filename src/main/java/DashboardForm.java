    private void btnBorrowActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBorrowActionPerformed
        int row = tblBooks.getSelectedRow();

if (row == -1) {

JOptionPane.showMessageDialog(
this,
"Please select a book first.");

return;
}

int copies = Integer.parseInt(
tblBooks.getValueAt(row, 3).toString());

if (copies > 0) {
    

copies--;

tblBooks.setValueAt(
copies,
row,
3);

try {

    Connection con =
            DBconnection.getConnection();

    PreparedStatement ps =
            con.prepareStatement(
            "UPDATE books SET copies=? WHERE book_id=?");

    ps.setInt(1, copies);

    ps.setString(
            2,
            tblBooks.getValueAt(row,0).toString());

    ps.executeUpdate();
    
    String bookID =
tblBooks.getValueAt(row, 0).toString();

String bookTitle =
tblBooks.getValueAt(row, 1).toString();
    
    PreparedStatement borrowPs =
        con.prepareStatement(
        "INSERT INTO borrow_records(student_id, book_id, book_title, borrow_date, status) VALUES(?,?,?,NOW(),?)");
    
    System.out.println("Borrow ID = " + currentStudentID);
    
    borrowPs.setString(1, currentStudentID);

borrowPs.setString(1, currentStudentID);
borrowPs.setString(2, bookID);
borrowPs.setString(3, bookTitle);
borrowPs.setString(4, "Borrowed");

borrowPs.executeUpdate();

} catch(Exception e) {

    JOptionPane.showMessageDialog(
            this,
            e.getMessage());

}

JOptionPane.showMessageDialog(
this,
"Book borrowed successfully!");



String dateTime =
java.time.LocalDateTime.now()
.format(
java.time.format.DateTimeFormatter.ofPattern(
"yyyy-MM-dd hh:mm:ss a"));

records.add(new String[]{
    dateTime,
    "BORROW",
    tblBooks.getValueAt(row, 0).toString(),
    tblBooks.getValueAt(row, 1).toString()
});

} else {

JOptionPane.showMessageDialog(
this,
"No copies available.");
}
    }//GEN-LAST:event_btnBorrowActionPerformed

