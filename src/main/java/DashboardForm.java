    private void loadBooks() {

    DefaultTableModel model =
            (DefaultTableModel) tblBooks.getModel();

    model.setRowCount(0);

    try {

        Connection con =
                DBconnection.getConnection();

        Statement st =
                con.createStatement();

        ResultSet rs =
                st.executeQuery("SELECT * FROM books");

        while(rs.next()) {

            model.addRow(new Object[]{

                rs.getString("book_id"),
                rs.getString("title"),
                rs.getString("author"),
                rs.getInt("copies")

            });

        }

    } catch(Exception e) {

        JOptionPane.showMessageDialog(
                this,
                e.getMessage());

    }
}
