    private void btnSearchActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSearchActionPerformed
        String keyword = txtSearch.getText().toLowerCase();

for (int i = 0; i < tblBooks.getRowCount(); i++) {

String id = tblBooks.getValueAt(i, 0).toString().toLowerCase();

String title = tblBooks.getValueAt(i, 1).toString().toLowerCase();

String author = tblBooks.getValueAt(i, 2).toString().toLowerCase();

if (id.contains(keyword)
|| title.contains(keyword)
|| author.contains(keyword)) {

tblBooks.setRowSelectionInterval(i, i);

return;
}
}

JOptionPane.showMessageDialog(
this,
"Book not found.");
    }//GEN-LAST:event_btnSearchActionPerformed

